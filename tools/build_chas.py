"""Build js/chas.js from data/chas-site.json (teas taken from clubedotempero.com/chas/).

Wholesale price rule (from the partners): site price minus 25%, per package,
times 10 packages per fardo/fitinha:  fardo = site_price * 0.75 * 10

Teas that already exist in the PDF catalog keep the catalog price and are only
tagged so they also show up under "Chás". The script prints a report comparing
both prices so differences are visible.

Usage: python3 tools/build_chas.py
"""
import json, os, re, unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def norm(s):
    s = unicodedata.normalize('NFKD', s).encode('ascii', 'ignore').decode().lower()
    return re.sub(r'[^a-z0-9]+', ' ', s).strip()


def cents(v):
    return int(round(v * 100))


def main():
    site = json.load(open(os.path.join(ROOT, 'data', 'chas-site.json'), encoding='utf-8'))
    catalog = json.load(open(os.path.join(ROOT, 'data', 'catalog.json'), encoding='utf-8'))
    by_name = {norm(p['name']): p for p in catalog['products']}
    ids = {p['id'] for p in catalog['products']}
    factor = (1 - site['discount']) * site['unitsPerPack']
    next_code = max(int(p['code']) for p in catalog['products']) + 1

    existing, new, report = [], [], []
    for t in site['products']:
        wholesale = [{'size': size, 'price': cents(price * factor) / 100} for size, price in t['retail'].items()]
        match = by_name.get(norm(t['name']))
        if match:
            existing.append(match['id'])
            cat = {v['size']: v['price'] for v in match['variants']}
            for w in wholesale:
                c = cat.get(w['size'])
                flag = 'igual' if c is not None and cents(c) == cents(w['price']) else ('NÃO NO CATÁLOGO' if c is None else 'DIFERENTE')
                report.append(f"  já existe  {t['name']:<28} {w['size']:>6}  catálogo={c!s:>8}  site-25%={w['price']:>8.2f}  {flag}")
            continue
        pid = re.sub(r'[^a-z0-9]+', '-', norm(t['name'])).strip('-')
        assert pid not in ids, pid
        ids.add(pid)
        new.append({
            'id': pid,
            'code': f'{next_code:03d}',
            'name': t['name'],
            'category': 'Chás',
            'use': t['description'],
            'image': site['imageBase'] + t['image'],
            'imageRemote': True,
            'source': 'site',
            'variants': wholesale,
        })
        next_code += 1
        report.append(f"  novo       {t['name']:<28} " + '  '.join(f"{w['size']}=R$ {w['price']:.2f}" for w in wholesale))

    out = {'source': site['source'], 'fetchedAt': site['fetchedAt'], 'rule': 'preço do site - 25% x 10 pacotes',
           'existingIds': existing, 'products': new}
    with open(os.path.join(ROOT, 'js', 'chas.js'), 'w', encoding='utf-8') as f:
        f.write('// Auto-generated by tools/build_chas.py from data/chas-site.json. Do not edit by hand.\n')
        f.write('(typeof window !== "undefined" ? window : globalThis).CDT_CHAS = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n')
    print('\n'.join(report))
    print(f'{len(site["products"])} chás no site: {len(existing)} já estavam no catálogo, {len(new)} novos')


if __name__ == '__main__':
    main()
